const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm')
const calc=require('../miniprogram/utils/schedule'),demo=require('../miniprogram/data/demo')
let page,navigation='',cloudCalls=0
const storage={}
const wx={getStorageSync:k=>storage[k],setStorageSync:(k,v)=>storage[k]=v,removeStorageSync:k=>delete storage[k],showToast(){},navigateTo:o=>navigation=o.url,showModal:o=>o.success({confirm:true}),cloud:{init(){cloudCalls++}}}
const source=fs.readFileSync(require.resolve('../miniprogram/pages/index/index'),'utf8')
vm.runInNewContext(source,{wx,Page:p=>page=p,require:id=>id.endsWith('/schedule')?calc:id.endsWith('/demo')?demo:id.endsWith('/local-notifications')?{reconcile:async()=>{}}:{},Date,Array,Number,Object,clearTimeout,setTimeout})
page.setData=o=>Object.assign(page.data,o)
page.onLoad();page.onShow();page.openLogin();assert.equal(navigation,'/pages/login/login')
assert.equal(cloudCalls,0);assert.doesNotMatch(source,/wx\.cloud|requestSubscribeMessage/)
page.importDemo();assert.equal(page.data.connected,true);assert.equal(page.data.demoMode,true)
page.pickDay({currentTarget:{dataset:{date:'2026-10-06'}}});assert.equal(page.data.courses.length,4)
page.changeTheme({currentTarget:{dataset:{theme:'amber'}}});assert.equal(storage['guga-theme'],'amber')
page.exitDemo();assert.equal(page.data.connected,false);assert.equal(cloudCalls,0)
const template=fs.readFileSync(require.resolve('../miniprogram/pages/index/index.wxml'),'utf8')
assert.doesNotMatch(template,/发送微信|reserveNight|testNightSummary|inset/)
assert.doesNotMatch(template,/bindtap="importDemo"|离线演示导入|不连接学校，也可以先体验/)
assert.match(template,/课表有变动时，重新登录即可刷新/)
const reminders=fs.readFileSync(require.resolve('../miniprogram/pages/notifications/notifications.wxml'),'utf8')
assert.equal((reminders.match(/（测试版，不稳定）/g)||[]).length,2)
assert.doesNotMatch(reminders,/不使用微信订阅|演示数据不会发送通知|更换课表后会更新/)
const styles=fs.readFileSync(require.resolve('../miniprogram/pages/index/index.wxss'),'utf8')
assert.doesNotMatch(styles,/var\(--|inset:|gap:/)
console.log('PASS: Android login navigation, offline demo, four-course day, theme persistence, exit restoration, no WeChat service calls, explicit compatible layout')
