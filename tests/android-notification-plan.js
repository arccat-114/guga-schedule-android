const assert=require('node:assert/strict')
const calc=require('../miniprogram/utils/schedule')
const {settings,buildPlan,preview}=require('../miniprogram/utils/notification-plan')
const model={firstMonday:'2026-10-12',courses:[{name:'测试课',day:2,weeks:'11',start:'00:10',end:'01:00',startSection:1,endSection:1,room:'A101'}]}
const options={summaryEnabled:true,summaryTime:'20:30',courseEnabled:true,leadMinutes:30}
const now=calc.timestamp('2026-10-12','19:00')
const plan=buildPlan(model,options,now)
const first=plan.jobs.find(j=>j.kind==='course')
assert.equal(first.at,calc.timestamp('2026-10-12','23:40'))
assert.equal(first.date,'2026-10-13')
assert.equal(plan.jobs.filter(j=>j.kind==='course').length,2)
assert.match(plan.jobs.find(j=>j.kind==='summary').body,/1次上课/)
assert.ok(plan.jobs.every(j=>j.at>now))
assert.equal(new Set(plan.jobs.map(j=>j.id)).size,plan.jobs.length)
assert.equal(buildPlan(model,{...options,summaryEnabled:false,courseEnabled:false},now).jobs.length,0)
assert.equal(buildPlan(model,options,calc.timestamp('2027-01-01','00:00')).jobs.length,0)
for(const leadMinutes of ['-1','1.5','abc','1441',''])assert.throws(()=>settings({...options,leadMinutes}),/分钟/)
for(const summaryTime of ['24:00','12:60','abc',''])assert.throws(()=>settings({...options,summaryTime}),/时间/)
assert.equal(settings({...options,leadMinutes:'0'}).leadMinutes,0)
const summaryPreview=preview(model,'summary',now),coursePreview=preview(model,'course',now)
assert.equal(summaryPreview.body,plan.jobs.find(j=>j.kind==='summary').body)
assert.equal(coursePreview.body,first.body)
assert.equal(coursePreview.title,first.title)
assert.throws(()=>preview({...model,courses:[]},'course',now),/没有未来课程/)
assert.throws(()=>preview(model,'unknown',now),/未支持/)
console.log('PASS: custom summary/lead validation, cross-midnight course reminder, unique jobs, expired term and disabled settings; planning only, no native delivery')
